  static dynamic _value(dynamic value) {
    if (value is Map) return sanitize(Map<String, dynamic>.from(value));
    if (value is List) return value.map(_value).toList(growable: false);
    return value;
  }

  static Map<String, dynamic> sanitize(Map<String, dynamic> json) {
    if ((json.containsKey('ownership_proof') ||
            json.containsKey('owner_phone')) &&
        json['status'] != null &&
        json['status'] != '' &&
        !const {
          'accepted',
          'approved',
          'published',
          'active',
          'available',
        }.contains(json['status'])) {
      return {};
    }
    return {
      for (final MapEntry<String, dynamic> field in json.entries)
        if (_fields.contains(field.key)) field.key: _value(field.value),
    };
  }
