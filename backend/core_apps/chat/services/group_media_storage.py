"""Dedicated private filesystem. No MEDIA_URL or user-selected storage keys."""

import hashlib
import os
import tempfile
import uuid
from datetime import timedelta
from pathlib import Path
from django.conf import settings
from django.db import transaction
from django.utils import timezone
from rest_framework.exceptions import ValidationError
from core_apps.chat.models import ChatAttachment
from .group_access import authorize
from .group_limits import ChatConflict, ChatUnavailable, limits
from .group_media_validation import inspect_image, inspect_voice


def private_root():
    root = Path(
        getattr(
            settings,
            "CHAT_PRIVATE_MEDIA_ROOT",
            Path(settings.BASE_DIR) / "private_chat_media",
        )
    )
    root.mkdir(mode=0o700, parents=True, exist_ok=True)
    return root


def private_path(key):
    # Keys are generated by this module; still reject corrupted DB traversal.
    if Path(key).name != key or key.startswith("."):
        raise ChatUnavailable()
    return private_root() / key


def upload_attachment(
    conversation, user, upload, client_upload_id, kind, supplied_hash=None
):
    try:
        upload_id = uuid.UUID(str(client_upload_id))
    except (TypeError, ValueError):
        raise ValidationError({"client_upload_id": "Supply a UUID."})
    if kind not in {"image", "voice"}:
        raise ValidationError({"kind": "Choose image or voice."})
    _, initial, _ = authorize(conversation, user, action="upload_attachment")
    cap = limits()[f"{kind}_max_bytes"]
    keys, persisted = [], False
    try:
        with tempfile.NamedTemporaryFile(dir=private_root(), prefix="staging-") as temp:
            digest, size = hashlib.sha256(), 0
            for chunk in upload.chunks():
                size += len(chunk)
                if size > cap:
                    raise ValidationError(
                        {"file": "Attachment exceeds the byte limit."}
                    )
                digest.update(chunk)
                temp.write(chunk)
            temp.flush()
            if size == 0 or (
                supplied_hash and supplied_hash.lower() != digest.hexdigest()
            ):
                raise ValidationError(
                    {"file": "Attachment is empty or its checksum does not match."}
                )
            fingerprint = hashlib.sha256(
                f"{kind}:{digest.hexdigest()}".encode()
            ).hexdigest()
            # Look up first: a retry does not repeat expensive media processing.
            existing = ChatAttachment.objects.filter(
                conversation=conversation, uploader=user, client_upload_id=upload_id
            ).first()
            if existing:
                if (
                    existing.fingerprint != fingerprint
                    or existing.membership_period != initial.membership_period
                ):
                    raise ChatConflict()
                authorize(conversation, user, action="upload_attachment")
                if existing.state not in {"ready", "attached"}:
                    raise ChatConflict(
                        "This attachment is no longer available. Select the media again."
                    )
                return existing
            content, thumbnail, metadata = (
                inspect_image if kind == "image" else inspect_voice
            )(temp.name)
        if len(content) > cap:
            raise ValidationError(
                {"file": "Processed attachment exceeds the byte limit."}
            )
        key = f"{uuid.uuid4().hex}.{'jpg' if kind == 'image' else 'm4a'}"
        thumb_key = f"{uuid.uuid4().hex}.jpg" if thumbnail else ""
        for name, body in [(key, content), (thumb_key, thumbnail)]:
            if name:
                keys.append(name)
                with open(private_path(name), "xb") as target:
                    os.chmod(target.name, 0o600)
                    target.write(body)
        with transaction.atomic():
            conversation, participant, _ = authorize(
                conversation, user, action="upload_attachment", lock=True
            )
            if participant.membership_period != initial.membership_period:
                raise ChatConflict("Membership changed during upload.")
            existing = ChatAttachment.objects.filter(
                conversation=conversation, uploader=user, client_upload_id=upload_id
            ).first()
            if existing:
                if existing.fingerprint != fingerprint:
                    raise ChatConflict()
                return existing
            result = ChatAttachment.objects.create(
                conversation=conversation,
                uploader=user,
                client_upload_id=upload_id,
                kind=kind,
                membership_period=participant.membership_period,
                fingerprint=fingerprint,
                storage_key=key,
                thumbnail_key=thumb_key,
                byte_size=len(content),
                **metadata,
            )
        persisted = True
        return result
    except OSError as exc:
        raise ChatUnavailable("Private media storage is unavailable.") from exc
    finally:
        if not persisted:
            for key in keys:
                private_path(key).unlink(missing_ok=True)


def cleanup_orphans():
    from core_apps.features.planning_models import HousingGroup

    cutoff = timezone.now() - timedelta(hours=limits()["orphan_retention_hours"])
    count = 0
    candidates = ChatAttachment.objects.filter(
        state="ready", message__isnull=True, created_at__lt=cutoff
    )
    for item in candidates.select_related("conversation"):
        with transaction.atomic():
            HousingGroup.objects.select_for_update().get(
                pk=item.conversation.housing_group_id
            )
            locked = ChatAttachment.objects.select_for_update().get(pk=item.pk)
            if locked.state != "ready" or locked.message_id:
                continue
            locked.state = "expired"
            locked.save(update_fields=["state", "updated_at"])
            transaction.on_commit(lambda item=locked: remove_files(item))
            count += 1
    # Files left by a crash before metadata commit are also bounded by retention.
    for item in ChatAttachment.objects.filter(
        state__in=["revoked", "expired"]
    ).iterator():
        remove_files(item)
    references = set(
        ChatAttachment.objects.values_list("storage_key", flat=True)
    ) | set(ChatAttachment.objects.values_list("thumbnail_key", flat=True))
    for path in private_root().iterdir():
        if (
            path.is_file()
            and path.name not in references
            and path.stat().st_mtime < cutoff.timestamp()
        ):
            path.unlink(missing_ok=True)
    return count


def remove_files(attachment):
    for key in (attachment.storage_key, attachment.thumbnail_key):
        if key:
            private_path(key).unlink(missing_ok=True)
